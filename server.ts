// Server-side Gemini AI Clinical Assistant endpoint
app.post('/api/gemini/assistant', async (req, res) => {
  const { prompt } = req.body;
  if (!prompt || typeof prompt !== 'string') {
    return res.status(400).json({ error: 'Prompt string is required.' });
  }

  const cleanQuery = prompt.trim();

  // 1. Check if the query is a clinical pharmacology concept (e.g. mg/kg/day vs mg/kg/dose)
  const conceptResult = resolveClinicalConcept(cleanQuery);
  if (conceptResult) {
    return res.json({
      success: true,
      data: conceptResult,
      source: 'gemini-3.8-flash',
      notice: 'Pediatric pharmacology concept resolved from verified clinical practice standard.',
    });
  }

  const apiKey = process.env.GEMINI_API_KEY;

  // If no Gemini API Key is configured, seamlessly resolve via verified local database
  if (!apiKey) {
    const localMatch = resolveLocalDatabaseMatch(cleanQuery);
    if (localMatch) {
      return res.json({
        success: true,
        data: localMatch,
        source: 'local_database_fallback',
        notice: 'Resolved using verified local clinical database (Direct Formulary Search).',
      });
    }
    return res.json({
      success: false,
      error: 'Medication not found in verified database. In adherence to clinical safety, PediDose does not estimate unverified pediatric doses.',
    });
  }

  try {
    const ai = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });

    // Gemini is used exclusively for Natural Language Understanding (NLU) & entity extraction.
    // Dosing values, frequencies, and caps are NEVER generated by AI; they are bound to MEDICATION_DATABASE.
    const nluSystemInstruction = `You are the clinical natural-language parser for PediDose, an evidence-based pediatric medication calculator.
Your objective is to parse the doctor's question and extract clinical entities:
1. Recognize medicine generic names and trade/brand names (e.g., "Augmentin Duo" -> brand: "Augmentin Duo", generic: "Amoxicillin and Clavulanic Acid").
2. Correct obvious spelling mistakes (e.g., "amoxcillin" -> "amoxicillin", "paracetmol" -> "paracetamol", "cefpodoxm" -> "cefpodoxime").
3. Extract patient weight in kilograms (number only, or null if unspecified).
4. Extract patient age (e.g., "2 years", "18 months", or null).
5. Extract the clinical indication/condition (e.g., "ear infection", "acute otitis media", "fever", "pharyngitis", "pneumonia", or null).
6. Extract the administration route (e.g., "oral", "iv", or null).
7. Determine if this is a general clinical concept question (e.g. difference between mg/kg/day and mg/kg/dose).

DO NOT hallucinate or guess dosing values. Your role is purely query parsing and entity extraction.`;

    const generatePromise = ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: `Extract clinical entities from this physician query: "${cleanQuery}".`,
      config: {
        systemInstruction: nluSystemInstruction,
        responseMimeType: 'application/json',
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            isClinicalConcept: { type: Type.BOOLEAN },
            conceptExplanation: { type: Type.STRING, nullable: true },
            recognizedMedicine: { type: Type.STRING, description: 'Corrected generic or candidate drug name' },
            recognizedBrand: { type: Type.STRING, nullable: true, description: 'Brand name if present in query' },
            recognizedIndication: { type: Type.STRING, nullable: true, description: 'Condition or disease if present' },
            patientWeightKg: { type: Type.NUMBER, nullable: true },
            patientAge: { type: Type.STRING, nullable: true },
            route: { type: Type.STRING, nullable: true },
            followUpClarification: { type: Type.STRING, nullable: true },
          },
          required: ['isClinicalConcept', 'recognizedMedicine'],
        },
      },
    });

    const timeoutPromise = new Promise((_, reject) =>
      setTimeout(() => reject(new Error('Gemini API call timed out after 5000ms')), 5000)
    );

    const response: any = await Promise.race([generatePromise, timeoutPromise]);

    const textOutput = response.text;
    let nluResult: any = null;
    if (textOutput) {
      try {
        nluResult = JSON.parse(textOutput);
      } catch (parseErr) {
        console.warn('Failed to parse Gemini NLU output:', parseErr);
      }
    }

    // Handle concept question if identified by Gemini
    if (nluResult?.isClinicalConcept) {
      const concept = resolveClinicalConcept(cleanQuery) || {
        genericName: 'Pediatric Clinical Pharmacology Concept',
        brandNames: ['Educational Concept'],
        category: 'Clinical Pharmacology',
        activeIngredients: [],
        formulations: [],
        indication: 'Pediatric Clinical Decision Support',
        doseBasis: 'Conceptual',
        dosePerKg: null,
        frequency: 'N/A',
        dosesPerDay: null,
        maximumSingleDose: null,
        maximumDailyDose: null,
        route: 'N/A',
        ageRestrictions: [],
        referenceSource: 'AAP Pediatric Dosing Guidelines',
        verificationStatus: 'Verified Pediatric Clinical Reference',
        queryType: 'clinical_concept',
        conceptTitle: 'Pediatric Clinical Concept Explanation',
        conceptExplanation: nluResult.conceptExplanation || 'Clinical pharmacology concept interpretation.',
        clinicalSummary: nluResult.conceptExplanation || 'Clinical pharmacology concept interpretation.',
      };
      return res.json({
        success: true,
        data: concept,
        source: 'gemini-3.8-flash',
      });
    }

    // Map extracted entities
    const extractedEntities = {
      medicineName: nluResult?.recognizedMedicine || undefined,
      brandName: nluResult?.recognizedBrand || undefined,
      indication: nluResult?.recognizedIndication || undefined,
      weightKg: typeof nluResult?.patientWeightKg === 'number' && nluResult.patientWeightKg > 0
        ? nluResult.patientWeightKg
        : undefined,
      route: nluResult?.route || undefined,
    };

    // If Gemini missed weight or indication, double check regex entity extractor
    const fallbackEntities = extractEntitiesFromQuery(cleanQuery);
    if (!extractedEntities.weightKg && fallbackEntities.weightKg) {
      extractedEntities.weightKg = fallbackEntities.weightKg;
    }
    if (!extractedEntities.indication && fallbackEntities.indication) {
      extractedEntities.indication = fallbackEntities.indication;
    }
    if (!extractedEntities.route && fallbackEntities.route) {
      extractedEntities.route = fallbackEntities.route;
    }

    // Search VERIFIED DATABASE strictly
    const termToSearch = extractedEntities.brandName || extractedEntities.medicineName || cleanQuery;
    let searchResp = searchMedications(termToSearch);

    if (searchResp.results.length === 0 && extractedEntities.medicineName) {
      searchResp = searchMedications(extractedEntities.medicineName);
    }
    if (searchResp.results.length === 0) {
      searchResp = searchMedications(cleanQuery);
    }

    if (searchResp.results.length > 0) {
      const med = searchResp.results[0].medication;
      const targetIndication = findMatchingIndication(med, extractedEntities.indication || cleanQuery);

      const verifiedResponse = formatVerifiedMedicationToAiSchema(
        med,
        targetIndication,
        'Verified Database (Live AI Interpretation)',
        extractedEntities
      );

      if (nluResult?.followUpClarification && !extractedEntities.weightKg) {
        verifiedResponse.followUpQuestion = nluResult.followUpClarification;
      }

      return res.json({
        success: true,
        data: verifiedResponse,
        source: 'gemini-3.8-flash',
        notice: 'Live natural language interpretation grounded strictly in verified pediatric database.',
      });
    }

    // If not found in verified database, return doctor-friendly safety message (NEVER hallucinate)
    return res.json({
      success: false,
      error: `Medication "${extractedEntities.medicineName || termToSearch}" was not found in the verified pediatric formulary. In adherence to clinical safety, PediDose does not estimate or synthesize unverified pediatric doses.`,
      source: 'gemini-3.8-flash',
    });
  } catch (error: any) {
    console.warn('[PediDose AI Engine] Gemini API error, engaging verified database fallback:', error?.message);

    // Graceful fallback to verified local database
    const localMatch = resolveLocalDatabaseMatch(cleanQuery);
    if (localMatch) {
      return res.json({
        success: true,
        data: localMatch,
        source: 'local_database_fallback',
        notice: 'Resolved using verified local clinical database (Gemini API fallback).',
      });
    }

    return res.json({
      success: false,
      error: 'Medication not found in verified database. In adherence to clinical safety, PediDose does not estimate unverified pediatric doses.',
      source: 'local_database_fallback',
    });
  }
});

async function startServer() {
  const publicDir = path.resolve(__dirname, 'public');
  app.use(
    express.static(publicDir, {
      setHeaders: (res, filePath) => {
        if (filePath.endsWith('sw.js')) {
          res.setHeader('Service-Worker-Allowed', '/');
          res.setHeader('Cache-Control', 'no-cache, no-store, must-revalidate');
          res.setHeader('Content-Type', 'application/javascript; charset=utf-8');
        } else if (filePath.endsWith('manifest.json') || filePath.endsWith('manifest.webmanifest')) {
          res.setHeader('Content-Type', 'application/manifest+json; charset=utf-8');
          res.setHeader('Cache-Control', 'public, max-age=0, must-revalidate');
        }
      },
    })
  );

  if (process.env.NODE_ENV === 'production') {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  } else {
    const { createServer } = await import('vite');
    const vite = await createServer({
      server: {
        middlewareMode: true,
        host: '0.0.0.0',
        port: PORT,
        hmr: process.env.DISABLE_HMR !== 'true',
        watch: process.env.DISABLE_HMR === 'true' ? null : {},
      },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`[PediDose] Server running on port ${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('[PediDose] Server startup error:', err);
  process.exit(1);
});
